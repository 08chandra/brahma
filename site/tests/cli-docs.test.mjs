// Tests for scripts/gen-cli.mjs against a fixture captured from the real
// `brahma --experimental-dump-help` output (a subset: `company` with `create` and
// `mode`, `log`, and the hidden `dev` group with one subcommand).
//
// Run: npm test (node --test).

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generate, escapeInline, synopsis } from '../scripts/gen-cli.mjs';

const fixture = JSON.parse(
  readFileSync(fileURLToPath(new URL('./fixtures/cli-dump.json', import.meta.url)), 'utf8'),
);

function run() {
  const outDir = mkdtempSync(join(tmpdir(), 'cli-docs-'));
  const written = generate(fixture, outDir);
  const rel = written.map((p) => relative(outDir, p)).sort();
  const read = (p) => readFileSync(join(outDir, p), 'utf8');
  return { outDir, written, rel, read, cleanup: () => rmSync(outDir, { recursive: true, force: true }) };
}

// Every command node reachable through displayed (shouldDisplay !== false) parents.
function displayedNodes(node, path = []) {
  const out = [];
  for (const sub of node.subcommands ?? []) {
    if (sub.shouldDisplay === false) continue;
    const p = [...path, sub.commandName];
    out.push({ node: sub, path: p });
    out.push(...displayedNodes(sub, p));
  }
  return out;
}

test('writes index.md, company.md and company/create.md', () => {
  const r = run();
  try {
    assert.ok(r.rel.includes('index.md'));
    assert.ok(r.rel.includes('company.md'));
    assert.ok(r.rel.includes(join('company', 'create.md')));
    for (const p of r.written) assert.ok(existsSync(p), `returned path exists: ${p}`);
  } finally {
    r.cleanup();
  }
});

test('company/create.md documents --goal with title, description and sections', () => {
  const r = run();
  try {
    const page = r.read('company/create.md');
    assert.match(page, /^---\ntitle: "brahma company create"\n/);
    assert.match(page, /\ndescription: "[^"]+"\n/);
    assert.match(page, /\n---\n<!-- generated by scripts\/site-cli-docs\.sh; do not edit -->\n/);
    assert.ok(page.includes('--goal'));
    assert.match(page, /## Usage\n\n```text\nbrahma company create <name> \[--goal <goal>\]/);
    assert.match(page, /## Arguments\n/);
    assert.match(page, /## Options\n\n\| Flag \| Value \| Default \| Description \|/);
    assert.match(page, /\| `--goal` \| `<goal>` \| — \| What the company is for/);
    assert.ok(!/`-h, --help`/.test(page), 'the implicit help flag is not listed');
  } finally {
    r.cleanup();
  }
});

test('group pages link every displayed subcommand; defaults and values are listed', () => {
  const r = run();
  try {
    const company = r.read('company.md');
    assert.match(company, /## Subcommands\n/);
    assert.ok(company.includes('](/docs/cli/company/create/)'));
    assert.ok(company.includes('](/docs/cli/company/mode/)'));
    assert.match(company, /```text\nbrahma company <subcommand>\n```/);

    const mode = r.read('company/mode.md');
    assert.ok(mode.includes('`low`, `balanced`, `max`'), 'allValues are listed');

    const log = r.read('log.md');
    assert.match(log, /\| `--limit` \| `<limit>` \| `30` \|/);

    const index = r.read('index.md');
    assert.match(index, /^---\ntitle: "CLI reference"\n/);
    assert.ok(index.includes('](/docs/cli/company/)'));
    assert.ok(index.includes('](/docs/cli/log/)'));
  } finally {
    r.cleanup();
  }
});

test('every displayed subcommand in the fixture has a file; hidden ones do not', () => {
  const r = run();
  try {
    const nodes = displayedNodes(fixture.command);
    assert.ok(nodes.length >= 4);
    for (const { path } of nodes) {
      assert.ok(r.rel.includes(`${path.join('/')}.md`), `missing page for ${path.join(' ')}`);
    }
    assert.equal(r.rel.length, nodes.length + 1, 'one page per displayed command plus index.md');
    assert.ok(!r.rel.some((p) => p === 'dev.md' || p.startsWith('dev/')), 'hidden dev group skipped');
    assert.ok(!r.read('index.md').includes('/docs/cli/dev/'));
  } finally {
    r.cleanup();
  }
});

test('no output contains /Users/ or raw < outside code', () => {
  const r = run();
  try {
    for (const p of r.rel) {
      const page = r.read(p);
      assert.ok(!page.includes('/Users/'), `${p} contains /Users/`);
      const prose = page
        .replace(/<!-- generated by scripts\/site-cli-docs\.sh; do not edit -->/, '')
        .replace(/```[\s\S]*?```/g, '')
        .replace(/`[^`\n]*`/g, '');
      assert.ok(!prose.includes('<'), `${p} has a raw < outside code: ${prose.match(/.{0,30}<.{0,30}/)?.[0]}`);
    }
  } finally {
    r.cleanup();
  }
});

test('escapeInline keeps code spans, escapes markup and table pipes', () => {
  assert.equal(escapeInline('a <b> `c <d>` *e*'), 'a &lt;b&gt; `c <d>` \\*e\\*');
  assert.equal(escapeInline('x | y', { table: true }), 'x \\| y');
  assert.equal(escapeInline('`a|b`', { table: true }), '`a\\|b`');
  assert.equal(escapeInline('[link](x)'), '\\[link\\](x)');
  assert.equal(escapeInline('one ` tick'), 'one \\` tick');
  assert.equal(escapeInline('~a~ and ~~b~~'), '\\~a\\~ and \\~\\~b\\~\\~');
});

test('escapeInline escapes block starts in prose only, never before a digit', () => {
  assert.equal(escapeInline('0.0 to 0.9'), '0.0 to 0.9');
  assert.equal(escapeInline('1. step'), '1\\. step');
  assert.equal(escapeInline('2) second'), '2\\) second');
  assert.equal(escapeInline('# heading'), '\\# heading');
  assert.equal(escapeInline('- item'), '\\- item');
  assert.equal(escapeInline('0.0 to 0.9', { table: true }), '0.0 to 0.9');
  assert.equal(escapeInline('1. step', { table: true }), '1. step');
  assert.equal(escapeInline('#channel or @handle.', { table: true }), '#channel or @handle.');
});

test('escapeInline sets --flags in prose as code (no smart-dash rendering)', () => {
  assert.equal(escapeInline('optional with --demo live'), 'optional with `--demo` live');
  assert.equal(escapeInline("('brahma run --profile')"), "('brahma run `--profile`')");
  assert.equal(escapeInline('--all shows every one'), '`--all` shows every one');
  assert.equal(escapeInline('use `x --y` here'), 'use `x --y` here', 'existing code spans untouched');
  assert.equal(escapeInline('a -- b'), 'a -- b', 'a bare double dash is not a flag');
});

test('synopsis renders optional, repeating and flag arguments', () => {
  const args = [
    { kind: 'positional', valueName: 'co', isOptional: false, isRepeating: false },
    { kind: 'positional', valueName: 'words', isOptional: true, isRepeating: true },
    { kind: 'option', valueName: 'touch', isOptional: true, isRepeating: true, names: [{ kind: 'long', name: 'touch' }], preferredName: { kind: 'long', name: 'touch' } },
    { kind: 'flag', valueName: 'all', isOptional: true, isRepeating: false, names: [{ kind: 'long', name: 'all' }], preferredName: { kind: 'long', name: 'all' } },
    { kind: 'flag', valueName: 'quiet', isOptional: true, isRepeating: false, shouldDisplay: false, names: [{ kind: 'short', name: 'q' }], preferredName: { kind: 'short', name: 'q' } },
  ];
  assert.equal(
    synopsis(['brahma', 'x'], { arguments: args }),
    'brahma x <co> [<words> ...] [--touch <touch> ...] [--all]',
  );
});
