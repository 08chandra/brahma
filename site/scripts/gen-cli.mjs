#!/usr/bin/env node
// CLI reference generator: turns swift-argument-parser's JSON help dump
// (`brahma --experimental-dump-help`) into Starlight Markdown pages.
//
// Usage: node scripts/gen-cli.mjs <dump.json> <outDir>
//   e.g. node scripts/gen-cli.mjs .reports/cli-dump.json src/content/docs/docs/cli
// Normally run by scripts/site-cli-docs.sh, which builds the CLI and empties
// <outDir> first.
//
// Writes <outDir>/index.md (every top-level command with its abstract) and one
// <path>.md per displayed command, where <path> is the subcommand names joined by
// "/" (company/create.md → /docs/cli/company/create/). Commands and arguments with
// `shouldDisplay: false` are skipped, hidden commands with their whole subtree;
// the implicit -h/--help flag is not listed per command (the index mentions it).
// Each page: frontmatter (title, description, sidebar label), the generated-file
// marker, abstract and discussion, then Usage, Arguments, Options, Subcommands.
// Help text is escaped so it renders literally (no raw `<`, no stray emphasis).
//
// Zero dependencies: node:fs, node:path and node:url only.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MARKER = '<!-- generated by scripts/site-cli-docs.sh; do not edit -->';
const URL_BASE = '/docs/cli';
const NAME_PATTERN = /^[a-z0-9][a-z0-9-]*$/;
const USAGE_WIDTH = 78;

const displayed = (item) => item.shouldDisplay !== false;
const isHelpFlag = (arg) =>
  arg.kind === 'flag' && (arg.names ?? []).some((n) => n.kind === 'long' && n.name === 'help');
const visibleArgs = (cmd) => (cmd.arguments ?? []).filter((a) => displayed(a) && !isHelpFlag(a));
const visibleSubs = (cmd) => (cmd.subcommands ?? []).filter(displayed);
const oneLine = (text) => (text ?? '').replace(/\s+/g, ' ').trim();

function flagName(name) {
  return name.kind === 'long' ? `--${name.name}` : `-${name.name}`;
}

/** A Markdown code span for `text`; `|` is escaped inside table cells (GFM). */
export function code(text, { table = false } = {}) {
  const runs = text.match(/`+/g) ?? [];
  const ticks = '`'.repeat(Math.max(0, ...runs.map((r) => r.length)) + 1);
  const pad = runs.length > 0 || text.startsWith(' ') || text.endsWith(' ') ? ' ' : '';
  const body = table ? text.replace(/\|/g, '\\|') : text;
  return `${ticks}${pad}${body}${pad}${ticks}`;
}

function escapeProse(text, table) {
  let out = text
    .replace(/\\/g, '\\\\')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/([*_[\]`])/g, '\\$1')
    // `--flag` as code: mono, and safe from smart punctuation turning `--` into a dash.
    .replace(/(^|[\s(['"])(--[a-z][a-z0-9-]*)/g, '$1`$2`');
  if (table) out = out.replace(/\|/g, '\\|');
  return out;
}

/**
 * Escapes help text for inline Markdown. Backtick code spans are kept (only `|`
 * is escaped inside them in table cells); everything else renders literally.
 * Unbalanced backticks are escaped rather than treated as code.
 */
export function escapeInline(text, { table = false } = {}) {
  const flat = oneLine(text);
  const ticks = (flat.match(/`/g) ?? []).length;
  let out;
  if (ticks === 0 || ticks % 2 === 1) {
    out = escapeProse(flat, table);
  } else {
    out = flat
      .split(/(`[^`]*`)/)
      .map((part, i) => {
        if (i % 2 === 1) return table ? part.replace(/\|/g, '\\|') : part;
        return escapeProse(part, table);
      })
      .join('');
  }
  // A leading #, -, + or "1." would start a heading or list.
  return out.replace(/^([#+-]|\d+[.)])/, '\\$1');
}

function argToken(arg) {
  let token;
  if (arg.kind === 'positional') {
    token = `<${arg.valueName}>`;
  } else {
    const name = flagName(arg.preferredName ?? arg.names[0]);
    token = arg.kind === 'option' ? `${name} <${arg.valueName}>` : name;
  }
  if (arg.isRepeating) token += ' ...';
  return arg.isOptional || arg.kind === 'flag' ? `[${token}]` : token;
}

/** The one-line synopsis of a command: `brahma company create <name> [--goal <goal>] ...`. */
export function synopsis(path, cmd) {
  return [path.join(' '), ...visibleArgs(cmd).map(argToken)].join(' ');
}

/** Wraps a synopsis at word boundaries (never inside a [...] or <...> token). */
function wrapUsage(path, cmd) {
  const tokens = visibleArgs(cmd).map(argToken);
  const lines = [];
  let line = path.join(' ');
  for (const token of tokens) {
    if (line.length + 1 + token.length > USAGE_WIDTH && line.trim() !== '') {
      lines.push(line);
      line = `  ${token}`;
    } else {
      line += ` ${token}`;
    }
  }
  lines.push(line);
  return lines.join('\n');
}

function fence(text, lang = 'text') {
  const runs = text.match(/`{3,}/g) ?? [];
  const ticks = '`'.repeat(Math.max(2, ...runs.map((r) => r.length)) + 1);
  return `${ticks}${lang}\n${text}\n${ticks}`;
}

/** Discussion text: aligned, column-style paragraphs are fenced; prose is escaped. */
function renderDiscussion(text) {
  return text
    .trim()
    .split(/\n\s*\n/)
    .map((para) => {
      const lines = para.split('\n');
      const preformatted = lines.some((l) => /^\s/.test(l) || /\S {2,}\S/.test(l));
      return preformatted ? fence(para.replace(/\s+$/, '')) : escapeInline(para);
    })
    .join('\n\n');
}

function url(path) {
  return `${URL_BASE}/${path.join('/')}/`;
}

function frontmatter({ title, description, label }) {
  return [
    '---',
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    'sidebar:',
    `  label: ${JSON.stringify(label)}`,
    '---',
    MARKER,
  ].join('\n');
}

function table(header, rows) {
  return [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

const cell = (text) => (oneLine(text) === '' ? '—' : escapeInline(text, { table: true }));
const valuesList = (values) => values.map((v) => code(v, { table: true })).join(', ');

function argumentsSection(args) {
  const rows = args.map((a) => {
    const marks = [a.isOptional ? 'optional' : '', a.isRepeating ? 'repeatable' : ''].filter(Boolean);
    const name = code(`<${a.valueName}>`, { table: true }) + (marks.length ? ` (${marks.join(', ')})` : '');
    let help = cell(a.abstract);
    if (a.allValues?.length) help = `${help === '—' ? '' : `${help} `}One of: ${valuesList(a.allValues)}.`;
    const def = a.defaultValue !== undefined ? code(String(a.defaultValue), { table: true }) : '—';
    return [name, def, help];
  });
  return `## Arguments\n\n${table(['Argument', 'Default', 'Description'], rows)}`;
}

function optionsSection(args) {
  const rows = args.map((a) => {
    const names = code((a.names ?? []).map(flagName).join(', '), { table: true });
    let value = '—';
    if (a.kind === 'option') {
      value = a.allValues?.length ? valuesList(a.allValues) : code(`<${a.valueName}>`, { table: true });
    }
    if (a.isRepeating) value = `${value === '—' ? '' : `${value} `}(repeatable)`;
    const def = a.defaultValue !== undefined ? code(String(a.defaultValue), { table: true }) : '—';
    return [names, value, def, cell(a.abstract)];
  });
  return `## Options\n\n${table(['Flag', 'Value', 'Default', 'Description'], rows)}`;
}

function commandsTable(parentPath, subs) {
  const rows = subs.map((s) => {
    const path = [...parentPath, s.commandName];
    return [`[${code(['brahma', ...path].join(' '), { table: true })}](${url(path)})`, cell(s.abstract)];
  });
  return table(['Command', 'Description'], rows);
}

function describe(cmd, title) {
  const abstract = oneLine(cmd.abstract);
  if (abstract) return abstract;
  const discussion = oneLine(cmd.discussion).match(/^[^.]*\./)?.[0];
  return discussion ?? `Usage, arguments and options of ${title}.`;
}

function renderCommand(path, cmd) {
  const title = ['brahma', ...path].join(' ');
  const subs = visibleSubs(cmd);
  const args = visibleArgs(cmd);
  const positionals = args.filter((a) => a.kind === 'positional');
  const options = args.filter((a) => a.kind !== 'positional');

  const parts = [
    frontmatter({
      title,
      description: describe(cmd, title),
      label: subs.length > 0 ? 'Overview' : cmd.commandName,
    }),
  ];
  if (oneLine(cmd.abstract)) parts.push(escapeInline(cmd.abstract));
  if (oneLine(cmd.discussion)) parts.push(renderDiscussion(cmd.discussion));

  const usage = [];
  if (subs.length > 0) usage.push(`${title} <subcommand>`);
  if (subs.length === 0 || args.length > 0) usage.push(wrapUsage(['brahma', ...path], cmd));
  parts.push(`## Usage\n\n${fence(usage.join('\n'))}`);
  if (cmd.defaultSubcommand) {
    parts.push(`Without a subcommand, ${code(title)} runs ${code(`${title} ${cmd.defaultSubcommand}`)}.`);
  }

  if (positionals.length > 0) parts.push(argumentsSection(positionals));
  if (options.length > 0) parts.push(optionsSection(options));
  if (subs.length > 0) parts.push(`## Subcommands\n\n${commandsTable(path, subs)}`);
  return `${parts.join('\n\n')}\n`;
}

function renderIndex(root) {
  const subs = visibleSubs(root);
  const parts = [
    frontmatter({
      title: 'CLI reference',
      description: 'Every brahma command, its arguments and options, generated from the CLI’s own help.',
      label: 'Overview',
    }),
  ];
  if (oneLine(root.abstract)) parts.push(escapeInline(root.abstract));
  parts.push(
    'This reference is generated from the `brahma` command’s built-in help, so it matches the CLI it was built from. ' +
      'Every command also accepts `-h` / `--help`, which prints the same information in the terminal.',
  );
  parts.push(`## Usage\n\n${fence('brahma <subcommand>')}`);
  parts.push(`## Commands\n\n${commandsTable([], subs)}`);
  return `${parts.join('\n\n')}\n`;
}

/**
 * Writes the reference pages for `dump` (the parsed dump, or its `command`) into
 * `outDir`; returns the written file paths. Does not empty `outDir` first.
 */
export function generate(dump, outDir) {
  const root = dump.command ?? dump;
  const written = [];
  const write = (rel, text) => {
    const file = join(outDir, rel);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    written.push(file);
  };

  write('index.md', renderIndex(root));
  const walk = (cmd, path) => {
    for (const sub of visibleSubs(cmd)) {
      if (!NAME_PATTERN.test(sub.commandName)) {
        throw new Error(`gen-cli: unexpected command name ${JSON.stringify(sub.commandName)}`);
      }
      const subPath = [...path, sub.commandName];
      write(`${subPath.join('/')}.md`, renderCommand(subPath, sub));
      walk(sub, subPath);
    }
  };
  walk(root, []);
  return written;
}

function main() {
  const [dumpPath, outDir] = process.argv.slice(2);
  if (!dumpPath || !outDir) {
    console.error('usage: node scripts/gen-cli.mjs <dump.json> <outDir>');
    process.exit(2);
  }
  const dump = JSON.parse(readFileSync(dumpPath, 'utf8'));
  const written = generate(dump, resolve(outDir));
  console.log(`gen-cli: wrote ${written.length} pages to ${relative(process.cwd(), resolve(outDir)) || '.'}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
