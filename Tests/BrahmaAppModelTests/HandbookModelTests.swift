import Testing
import Foundation
import BrahmaCore
@testable import BrahmaAppModel

/// Plan ML Task 8: the owner's Handbook view model — the pack-ordered tree, auto pages, restricted sections, edit conflicts,
/// rollback, vouch, export and the `handbook` / `kb:<path>` / `memory` launch targets.
@MainActor @Suite(.scratch) struct HandbookModelTests {
    struct W {
        let app: AppModel, store: Store, paths: BrahmaPaths, acme: Company, ceo: Agent, cto: Agent, eng: Agent
        var pack: IndustryPack { store.catalog.pack(acme.packId)! }

        /// `kbWrite` as the owner, on the page's current revision.
        @discardableResult
        func write(_ path: String, _ body: String) throws -> Int {
            let base = try store.kbPages(companyId: acme.id, reader: .owner).first { $0.path == path }?.revision
            return try store.kbWrite(companyId: acme.id, by: .owner, path: path, body: body, baseRevision: base, knownValues: [],
                                     paths: paths).revision
        }

        /// The Acme handbook model, loaded.
        @MainActor func handbook() async throws -> HandbookModel {
            await app.load()
            #expect(app.selectedCompanyId == acme.id)
            app.select(.handbook)
            let hb = try #require(app.ensureHandbook())
            await hb.reload()
            return hb
        }
    }

    func world() throws -> W {
        let (store, paths) = try makeHome()
        let (acme, ceo, cto, eng) = try seedAcme(store, paths)
        try store.setOwnerTimeZone("UTC")
        return W(app: AppModel(store: store, paths: paths), store: store, paths: paths, acme: acme, ceo: ceo, cto: cto, eng: eng)
    }

    @Test func treeOrdersSectionsByPack() throws {
        let w = try world()
        try w.store.refreshAutoPages(companyId: w.acme.id)
        try w.write("Zeta", "# Zeta")
        try w.write("Alpha", "# Alpha")
        try w.write("Engineering/Runbooks", "# Runbooks")
        try w.write("Engineering/Architecture", "# Architecture")
        // A page whose parent has no page of its own still hangs under a placeholder node.
        try w.write("Ops notes/2026/Week one", "# Week one")
        let pages = try w.store.kbPages(companyId: w.acme.id, reader: .owner)
        let tree = HandbookTree.make(pages: pages, pack: w.pack)
        let packPaths = w.pack.handbook.map(\.path)
        #expect(Array(tree.map(\.path).prefix(packPaths.count)) == packPaths)
        #expect(Array(tree.map(\.path).dropFirst(packPaths.count)) == ["Alpha", "Ops notes", "Zeta"])
        let engineering = try #require(tree.first { $0.path == "Engineering" })
        #expect(engineering.children.map(\.title) == ["Architecture", "Runbooks"])
        let ops = try #require(tree.first { $0.path == "Ops notes" })
        #expect(!ops.isPage)
        #expect(ops.children.first?.children.first?.path == "Ops notes/2026/Week one")
        // Flattened rows keep the order, with depth.
        let rows = HandbookTree.rows(tree)
        let arch = try #require(rows.firstIndex { $0.node.path == "Engineering/Architecture" })
        #expect(rows[arch - 1].node.path == "Engineering")
        #expect(rows[arch].depth == 1)
    }

    @Test func autoPagesMarkedAndNotEditable() async throws {
        let w = try world()
        try w.store.refreshAutoPages(companyId: w.acme.id)
        let hb = try await w.handbook()
        let auto = HandbookTree.rows(hb.tree).filter { $0.node.chips.contains("AUTO") }.map(\.node.path)
        #expect(Set(auto) == Set(Handbook.autoPagePaths))
        #expect(auto.count == 5)
        await hb.select("Company/Roster")
        let view = try #require(hb.view)
        #expect(view.page.autoKind != nil)
        #expect(hb.canEdit == false)
        #expect(await hb.save(edit: "hijack", baseRevision: view.page.revision) == false)
        #expect(hb.error?.contains("generated by the engine") == true)
        // An owner page is editable.
        await hb.select("Engineering")
        #expect(hb.canEdit)
    }

    @Test func ownerSeesRestrictedSectionsMarked() async throws {
        let w = try world()
        try w.write("Engineering/Environments", """
            # Environments

            Staging and production.

            ## Credentials policy [restricted: cfo]

            Rotate monthly.

            ### Break-glass

            Call the CFO.
            """)
        let hb = try await w.handbook()
        await hb.select("Engineering/Environments")
        let blocks = hb.blocks
        let policy = try #require(blocks.first { $0.heading == "Credentials policy" })
        #expect(policy.restrictedChip == "RESTRICTED · cfo")
        #expect(policy.markdown.contains("Rotate monthly."))
        // A subsection inherits its parent's restriction.
        #expect(blocks.first { $0.heading == "Break-glass" }?.restrictedChip == "RESTRICTED · cfo")
        #expect(blocks.first { $0.heading == "Environments" }?.restrictedChip == nil)
        // The header line, in mono: path, revision, owner and update time.
        #expect(hb.headerLine.hasPrefix("kb:Engineering/Environments · REV 1 · @owner · UPDATED "))
        // A page-level restriction is a header chip.
        #expect(HandbookPresentation.restrictedChip([["@executive"], ["cfo", "ceo"]]) == "RESTRICTED · executive + ceo, cfo")
    }

    @Test func editConflictSurfaces() async throws {
        let w = try world()
        try w.write("Engineering/Notes", "# Notes\n\none")
        let hb = try await w.handbook()
        await hb.select("Engineering/Notes")
        #expect(hb.view?.revision == 1)
        try w.write("Engineering/Notes", "# Notes\n\ntwo")
        #expect(await hb.save(edit: "# Notes\n\nmine", baseRevision: 1) == false)
        #expect(hb.error == "kb:Engineering/Notes changed since revision 1 (now 2); kb_read it again and merge your edit")
        #expect(await hb.save(edit: "# Notes\n\nmine", baseRevision: 2))
        #expect(hb.error == nil)
        #expect(hb.view?.revision == 3)
        #expect(hb.view?.text.contains("mine") == true)
        #expect(hb.revisions.map(\.number) == [1, 2, 3])
    }

    @Test func rollbackFromApp() async throws {
        let w = try world()
        try w.write("Engineering/Notes", "# Notes\n\none")
        try w.write("Engineering/Notes", "# Notes\n\ntwo")
        let hb = try await w.handbook()
        await hb.select("Engineering/Notes")
        #expect(hb.canRollback == false)
        #expect(hb.revisions.map { HandbookPresentation.revisionLabel($0, handles: [:], timeZone: .gmt) }.first?
            .hasPrefix("REV 1 · +3 −0 lines · @owner · ") == true)
        await hb.show(revision: 1)
        #expect(hb.revision == 1)
        #expect(hb.view?.revision == 1)
        #expect(hb.view?.text.contains("one") == true)
        #expect(hb.canRollback)
        #expect(hb.canEdit == false, "an old revision is not edited")
        #expect(await hb.rollback(to: 1))
        #expect(hb.revision == nil)
        #expect(hb.view?.revision == 3)
        #expect(hb.view?.text.contains("one") == true)
        #expect(hb.revisions.last?.rollbackOf == 1)
    }

    @Test func vouchFromApp() async throws {
        let w = try world()
        let item = try w.store.createWorkItem(companyId: w.acme.id, by: .owner,
                                              draft: WorkItemDraft(type: .task, title: "Market notes", ownerId: w.eng.id))
        try w.store.markTainted(agentId: w.eng.id, source: "web page example.com")
        try w.store.kbWrite(companyId: w.acme.id, by: .agent(w.eng.id), path: "Research/Market", body: "# Market\n\nIt is big.",
                            itemId: item.id, knownValues: [], paths: w.paths)
        let hb = try await w.handbook()
        #expect(HandbookTree.rows(hb.tree).first { $0.node.path == "Research/Market" }?.node.chips == ["TAINTED"])
        await hb.select("Research/Market")
        #expect(hb.view?.tainted == true)
        #expect(hb.canVouch)
        #expect(await hb.vouch())
        #expect(hb.view?.tainted == false)
        #expect(hb.canVouch == false)
        #expect(HandbookTree.rows(hb.tree).first { $0.node.path == "Research/Market" }?.node.chips == [])
        // Status: the owner deprecates it; the tree shows the chip.
        #expect(await hb.setStatus(.deprecated))
        #expect(hb.view?.page.status == .deprecated)
        #expect(HandbookTree.rows(hb.tree).first { $0.node.path == "Research/Market" }?.node.chips == ["DEPRECATED"])
    }

    @Test func editOfTaintedPageIsExplicitVouch() async throws {
        let w = try world()
        let item = try w.store.createWorkItem(companyId: w.acme.id, by: .owner,
                                              draft: WorkItemDraft(type: .task, title: "Market notes", ownerId: w.eng.id))
        try w.store.markTainted(agentId: w.eng.id, source: "web page example.com")
        try w.store.kbWrite(companyId: w.acme.id, by: .agent(w.eng.id), path: "Research/Market", body: "# Market\n\nIt is big.",
                            itemId: item.id, knownValues: [], paths: w.paths)
        try w.write("Engineering/Notes", "# Notes")
        let hb = try await w.handbook()
        #expect(HandbookModel.editVouchNotice == "Saving vouches for the whole page, including agent-written text")
        // An untainted page saves plainly.
        await hb.select("Engineering/Notes")
        #expect(hb.editVouches == false)
        #expect(hb.saveTitle == "Save")
        // A tainted page: the owner's whole-page save clears the taint, so the sheet says it vouches.
        await hb.select("Research/Market")
        #expect(hb.canEdit)
        #expect(hb.editVouches)
        #expect(hb.saveTitle == "Save and vouch")
        let base = try #require(hb.view?.page.revision)
        #expect(await hb.save(edit: "# Market\n\nIt is big. Typo fixed.", baseRevision: base))
        #expect(hb.view?.page.tainted == false)
        #expect(hb.editVouches == false)
        #expect(hb.saveTitle == "Save")
    }

    @Test func exportRefusesNonEmptyFolder() async throws {
        let w = try world()
        let hb = try await w.handbook()
        let full = try tempDir()
        try Data("keep".utf8).write(to: full.appending(path: "mine.txt"))
        let refused = await hb.export(to: full)
        #expect(refused == .failure(.invalid(HandbookModel.exportNeedsEmptyFolder)))
        #expect(try FileManager.default.contentsOfDirectory(atPath: full.path) == ["mine.txt"])
        let empty = try tempDir()
        guard case .success(let n) = await hb.export(to: empty) else { Issue.record("export failed: \(hb.error ?? "")"); return }
        #expect(n > 1)
        #expect(FileManager.default.fileExists(atPath: empty.appending(path: "INDEX.md").path))
    }

    @Test func selectKBTarget() async throws {
        #expect(SelectTarget("handbook") == .handbook)
        #expect(SelectTarget("memory") == .memory)
        #expect(SelectTarget("kb:Engineering") == .kb(path: "Engineering"))
        #expect(SelectTarget("kb:Company/Org chart") == .kb(path: "Company/Org chart"))
        #expect(SelectTarget("kb:") == nil)
        let w = try world()
        await w.app.load()
        w.app.apply(.kb(path: "Engineering"))
        #expect(w.app.sidebarSelection == .handbook)
        let hb = try #require(w.app.handbook)
        #expect(hb.tab == .pages)
        try await eventually { hb.view?.page.path == "Engineering" }
        #expect(hb.selection == "Engineering")
        w.app.apply(.memory)
        #expect(w.app.sidebarSelection == .handbook)
        #expect(hb.tab == .memory)
        w.app.apply(.handbook)
        #expect(hb.tab == .pages)
        // Another company gets its own handbook.
        let globex = try #require(w.app.snapshot.companies.first { $0.company.name == "Globex" })
        await w.app.selectCompany(globex.id)
        #expect(w.app.handbook == nil)
        #expect(w.app.ensureHandbook()?.companyId == globex.id)
    }
}
