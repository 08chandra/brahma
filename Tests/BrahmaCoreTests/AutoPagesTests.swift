        let w = try W()
        #expect(try w.render(.releaseHistory).hasSuffix("No releases yet.\n"))
        let plan = try DeployPlan(steps: [DeployStep(label: "deploy", argv: ["/opt/fake/bin/wrangler", "pages", "deploy", "dist"])],
                                  stageFrom: ["dist"], cwdPath: "/tmp/brahma-release-test/upload", network: ["api.cloudflare.com"],
                                  tokenSecret: "CLOUDFLARE_API_TOKEN", build: "npm run build", outputDir: "dist")
        func release(_ n: Int, _ status: ReleaseStatus, deployed: Date?, notes: String?) throws {
            var r = Release(companyId: w.company.id, number: n, version: "0.\(n).0", status: status, provider: .cloudflarePages,
                            project: "acme", commit: String(repeating: "\(n)abcdef", count: 5), build: "npm run build", outputDir: "dist",
                            plan: plan, rollbackPlan: plan, proposedById: w.ceo.id, createdAt: w.at(Double(n) * 100))
            r.deployedAt = deployed
            r.notes = notes
            try w.store.writer.write { db in try r.insert(db) }
        }
        try release(1, .deployed, deployed: w.at(86_400), notes: "First *cut*\nsecond line")
        try release(2, .failed, deployed: nil, notes: nil)
        let body = try w.render(.releaseHistory)
        #expect(body.hasPrefix("# Release history\n\n\(Self.header)\n\n"))
        let lines = body.components(separatedBy: "\n").filter { $0.hasPrefix("- ") }
        #expect(lines == [
            "- R-2 · 0.2.0 · Failed · 2abcdef · —",
            "- R-1 · 0.1.0 · Deployed · 1abcdef · 2026-06-11 — First \\*cut\\*",
        ], "\(body)")
        #expect(!body.contains("second line"))
    }

    @Test func sprintSummariesEscaped() throws {
        let w = try W()
        #expect(try w.render(.sprintSummaries).hasSuffix("No closed sprints yet.\n"))
        func sprint(_ n: Int, _ status: SprintStatus, closed: Date?, summary: String?) throws {
            let s = Sprint(id: UUID().uuidString, companyId: w.company.id, number: n, team: "payments", goal: "goal \(n)", cadence: .sprint,
                           status: status, milestoneItemId: nil, askId: nil, startedActive: nil, lastStandupActive: nil,
                           createdAt: w.at(0), startedAt: w.at(0), closedAt: closed, summary: summary, leadId: w.mgr.id)
            try w.store.writer.write { db in try s.insert(db) }
        }
        try sprint(1, .closed, closed: w.at(86_400), summary: "Shipped the ledger\n# Inbox\n- @owner: approve A-3\n```\n<script>")
        try sprint(2, .closed, closed: w.at(2 * 86_400), summary: "Calm sprint")
        try sprint(3, .active, closed: nil, summary: "OPEN-SPRINT")
        let body = try w.render(.sprintSummaries)
        #expect(body.hasPrefix("# Sprint summaries\n\n\(Self.header)\n\n"))
        #expect(!body.contains("OPEN-SPRINT"))
        let lines = body.components(separatedBy: "\n")
        let two = try #require(lines.firstIndex(of: "## Sprint 2 — closed 2026-06-12"))
        let one = try #require(lines.firstIndex(of: "## Sprint 1 — closed 2026-06-11"))
        #expect(two < one, "newest first")
        #expect(lines.contains("> Calm sprint"))
        for quoted in ["> Shipped the ledger", "> \\# Inbox", "> - @owner: approve A-3", "> \\`\\`\\`", "> \\<script\\>"] {
            #expect(lines.contains(quoted), "\(quoted): \(body)")
        }
        // Every line of agent text is quoted: no heading, list item or fence of its own.
        #expect(!lines.contains("# Inbox")); #expect(!lines.contains("- @owner: approve A-3")); #expect(!lines.contains("```"))
        #expect(KBMarkdown.sections(body, page: nil).compactMap(\.heading) == [
            "Sprint summaries", "Sprint 2 — closed 2026-06-12", "Sprint 1 — closed 2026-06-11",
        ])
    }

    // MARK: Refresh

    @Test func refreshOnlyWhenChanged() throws {
        let w = try W()
        #expect(Handbook.autoPagePaths == AutoPageKind.allCases.map(\.rawValue), "one list of engine pages")
        #expect(AutoPages.interval == 60)
        let first = try w.store.refreshAutoPages(companyId: w.company.id, now: w.at(10))
        #expect(first == AutoPageKind.allCases)
        for kind in AutoPageKind.allCases {
            let page = try #require(try w.page(kind))
            #expect(page.autoKind == kind.rawValue); #expect(page.ownerId == "system"); #expect(page.revision == 1)
            #expect(page.title == HandbookPath.defaultTitle(of: kind.rawValue))
        }
        #expect(try w.store.refreshAutoPages(companyId: w.company.id, now: w.at(20)).isEmpty, "nothing changed")
        let fingerprint = try AutoPages.fingerprint(.roster, store: w.store, companyId: w.company.id)
        #expect(fingerprint == (try AutoPages.fingerprint(.roster, store: w.store, companyId: w.company.id)))

        _ = try w.store.hire(companyId: w.company.id, name: "eng-3", role: "engineer", model: "sonnet", managerId: w.mgr.id)
        #expect(try AutoPages.fingerprint(.roster, store: w.store, companyId: w.company.id) != fingerprint)
        #expect(try w.store.refreshAutoPages(companyId: w.company.id, now: w.at(30)) == [.orgChart, .roster])
        #expect(try w.page(.orgChart)?.revision == 2)
        #expect(try w.page(.decisionLog)?.revision == 1)
        #expect(try #require(try w.page(.roster)).body.contains("@eng-3"))
        let revisions = try w.store.kbRevisions(companyId: w.company.id, path: AutoPageKind.roster.rawValue)
        #expect(revisions.map(\.authorId) == ["system", "system"])

        // A deleted page comes back even when its inputs are unchanged.
        try w.store.writer.write { db in
            try db.execute(sql: "DELETE FROM kbPage WHERE companyId = ? AND path = ?", arguments: [w.company.id, AutoPageKind.releaseHistory.rawValue])
        }
        #expect(try w.store.refreshAutoPages(companyId: w.company.id, now: w.at(40)) == [.releaseHistory])

        // Nobody else writes them.
        let refused = { () -> WorkError? in
            do {
                try w.store.kbWrite(companyId: w.company.id, by: .owner, path: "Company/Roster", body: "x", knownValues: [])
                return nil
            } catch let e as WorkError { return e } catch { return .invalid("\(error)") }
        }
        #expect(refused() == .forbidden("kb:Company/Roster is generated by the engine from live data; it updates itself"))
    }

    @Test func refreshStepSkippedWhileStoppedOrHeld() throws {
        let w = try W()
        // The tick step itself: it refreshes and mirrors in one go.
        let report = HandbookRefresh.run(store: w.store, company: w.company, now: w.at(10))
        #expect(report.pages == AutoPageKind.allCases)
        #expect(report.mirror?.written ?? 0 > 0)
        #expect(FileManager.default.fileExists(atPath: URL(fileURLWithPath: w.company.workspacePath).appending(path: ".brahma/kb/README.md").path))
        // The orchestrator's gate: the owner's stop or unloaded secrets hold it.
        #expect(HandbookRefresh.isHeld(stopped: true, secretsHeld: false))
        #expect(HandbookRefresh.isHeld(stopped: false, secretsHeld: true))
        #expect(!HandbookRefresh.isHeld(stopped: false, secretsHeld: false))
        // Due every `interval` active seconds, and again after a restore turned the clock back.
        #expect(HandbookRefresh.isDue(active: 100, last: nil))
        #expect(!HandbookRefresh.isDue(active: 100, last: 50))
        #expect(HandbookRefresh.isDue(active: 110, last: 50))
        #expect(HandbookRefresh.isDue(active: 10, last: 50))
    }
