    static let header = "_Generated by Brahma from live data; it can't be edited._"
    static let t0 = Date(timeIntervalSince1970: 1_781_107_200) // 2026-06-10 16:00 UTC

    /// Acme in UTC: ceo (executive), mgr-1 ← {eng-1, eng-2} (team payments), a killed old-1, and a vacancy qa-1 under mgr-1.
    struct W {
        let store: Store, company: Company, root: URL
        let ceo: Agent, mgr: Agent, eng1: Agent, eng2: Agent, old: Agent

        init() throws {
            let s = try Store.inMemory()
            root = try tempDir()
            let c = try s.createCompany(name: "Acme", goal: "g", workspacesRoot: root.appending(path: "ws"))
            try s.setOwnerTimeZone("UTC")
            store = s; company = c
            ceo = try s.hire(companyId: c.id, name: "ceo", role: "ceo", model: "sonnet")
            mgr = try s.hire(companyId: c.id, name: "mgr-1", role: "manager", model: "sonnet", managerId: ceo.id)
            eng1 = try s.hire(companyId: c.id, name: "eng-1", role: "engineer", model: "sonnet", managerId: mgr.id, team: "payments")
            eng2 = try s.hire(companyId: c.id, name: "eng-2", role: "engineer", model: "sonnet", managerId: mgr.id, team: "payments")
            old = try s.hire(companyId: c.id, name: "old-1", role: "engineer", model: "sonnet", managerId: mgr.id)
            try s.writer.write { db in
                try db.execute(sql: "UPDATE agent SET state = 'killed' WHERE id = ?", arguments: [old.id])
                var v = OrgVacancy(id: nil, companyId: c.id, role: "qa", handle: "qa-1", managerHandle: "mgr-1", team: "payments",
                                   createdAt: AutoPagesTests.t0, filledAt: nil)
                try v.insert(db)
            }
        }

        func title(_ role: String) -> String { store.catalog.template(role: role, pack: company.packId).title }

        func render(_ kind: AutoPageKind) throws -> String {
            try AutoPages.render(kind, store: store, companyId: company.id, now: AutoPagesTests.t0, tz: TimeZone(identifier: "UTC")!)
        }

        func agent(_ a: Agent) throws -> Agent { try #require(try store.agent(id: a.id)) }

        func at(_ seconds: TimeInterval) -> Date { AutoPagesTests.t0.addingTimeInterval(seconds) }

        /// An ask filed by `by`, then decided as `status` by `decidedBy` at `at(decided)` (the rows as the decision paths leave them).
        @discardableResult
        func ask(_ kind: AskKind = .other, category: String? = "tooling", by: Agent?, title: String, summary: String = "the summary",
                 status: AskStatus, decidedBy: String? = "owner", decided: TimeInterval = 60) throws -> Ask {
            let sender: Sender = by.map { .agent($0.id) } ?? .system
            let ask: Ask
            if kind == .info {
                ask = try store.requestFromOwner(companyId: company.id, by: sender, title: title, question: summary, now: at(0))
            } else {
                ask = try store.propose(companyId: company.id, by: sender, kind: kind, category: category, title: title,
                                        summary: summary, now: at(0))
            }
            try store.writer.write { db in
                try db.execute(sql: """
                    UPDATE ask SET status = ?, decidedBy = ?, ownerDecidedAt = ?, ownerAnswer = ?, ownerNote = ?, updatedAt = ?
                    WHERE id = ?
                    """, arguments: [status.rawValue, decidedBy, at(decided), "ANSWER-TEXT-\(ask.number)", "NOTE-TEXT-\(ask.number)",
                                     at(decided), ask.id])
            }
            return try #require(try store.ask(id: ask.id))
        }

        func page(_ kind: AutoPageKind) throws -> KBPage? {
            try store.writer.read { db in try Store.kbPage(db: db, companyId: company.id, path: kind.rawValue) }
        }
    }

