/// Plan ML Task 5: the engine-rendered handbook pages (org chart, roster, decisions log, release history, sprint summaries).
@Suite(.scratch) struct AutoPagesTests {
    static let header = "_Generated by Brahma from live data; it can't be edited._"
    static let t0 = Date(timeIntervalSince1970: 1_781_107_200) // 2026-06-10 16:00 UTC

    /// Acme in UTC: ceo (executive), mgr-1 ← {eng-1, eng-2} (team payments), a killed old-1, and a vacancy qa-1 under mgr-1.
    struct W {
        let store: Store, company: Company, root: URL
        let ceo: Agent, mgr: Agent, eng1: Agent, eng2: Agent, old: Agent

        init() throws {
            let s = try Store.inMemory()
            root = try tempDir()
            let c = try s.createCompany(name: "Acme", goal: "g", workspacesRoot: root.appending(path: "ws"))
            try s.setOwnerTimeZone("UTC")
            store = s; company = c
            ceo = try s.hire(companyId: c.id, name: "ceo", role: "ceo", model: "sonnet")
            mgr = try s.hire(companyId: c.id, name: "mgr-1", role: "manager", model: "sonnet", managerId: ceo.id)
            eng1 = try s.hire(companyId: c.id, name: "eng-1", role: "engineer", model: "sonnet", managerId: mgr.id, team: "payments")
            eng2 = try s.hire(companyId: c.id, name: "eng-2", role: "engineer", model: "sonnet", managerId: mgr.id, team: "payments")
            old = try s.hire(companyId: c.id, name: "old-1", role: "engineer", model: "sonnet", managerId: mgr.id)
            try s.writer.write { db in
                try db.execute(sql: "UPDATE agent SET state = 'killed' WHERE id = ?", arguments: [old.id])
                var v = OrgVacancy(id: nil, companyId: c.id, role: "qa", handle: "qa-1", managerHandle: "mgr-1", team: "payments",
                                   createdAt: AutoPagesTests.t0, filledAt: nil)
                try v.insert(db)
            }
        }

        func title(_ role: String) -> String { store.catalog.template(role: role, pack: company.packId).title }

        func render(_ kind: AutoPageKind) throws -> String {
            try AutoPages.render(kind, store: store, companyId: company.id, now: AutoPagesTests.t0, tz: TimeZone(identifier: "UTC")!)
        }

        func agent(_ a: Agent) throws -> Agent { try #require(try store.agent(id: a.id)) }

        func at(_ seconds: TimeInterval) -> Date { AutoPagesTests.t0.addingTimeInterval(seconds) }

        /// An ask filed by `by`, then decided as `status` by `decidedBy` at `at(decided)` (the rows as the decision paths leave them).
        @discardableResult
        func ask(_ kind: AskKind = .other, category: String? = "tooling", by: Agent?, title: String, summary: String = "the summary",
                 status: AskStatus, decidedBy: String? = "owner", decided: TimeInterval = 60) throws -> Ask {
            let sender: Sender = by.map { .agent($0.id) } ?? .system
            let ask: Ask
            if kind == .info {
                ask = try store.requestFromOwner(companyId: company.id, by: sender, title: title, question: summary, now: at(0))
            } else {
                ask = try store.propose(companyId: company.id, by: sender, kind: kind, category: category, title: title,
                                        summary: summary, now: at(0))
            }
            try store.writer.write { db in
                try db.execute(sql: """
                    UPDATE ask SET status = ?, decidedBy = ?, ownerDecidedAt = ?, ownerAnswer = ?, ownerNote = ?, updatedAt = ?
                    WHERE id = ?
                    """, arguments: [status.rawValue, decidedBy, at(decided), "ANSWER-TEXT-\(ask.number)", "NOTE-TEXT-\(ask.number)",
                                     at(decided), ask.id])
            }
            return try #require(try store.ask(id: ask.id))
        }

        func page(_ kind: AutoPageKind) throws -> KBPage? {
            try store.writer.read { db in try Store.kbPage(db: db, companyId: company.id, path: kind.rawValue) }
        }
    }

    // MARK: Org chart and roster

    @Test func orgChartRendersTreeAndVacancies() throws {
        let w = try W()
        let body = try w.render(.orgChart)
        #expect(body.hasPrefix("# Org chart\n\n\(Self.header)\n\n"))
        let state = { (a: Agent) in try w.agent(a).state.rawValue }
        let expected = [
            "- @ceo — \(w.title("ceo")) · \(try state(w.ceo))",
            "  - @mgr-1 — \(w.title("manager")) · \(try state(w.mgr))",
            "    - @eng-1 — \(w.title("engineer")) · \(try state(w.eng1))",
            "    - @eng-2 — \(w.title("engineer")) · \(try state(w.eng2))",
            "    - (vacant) \(w.title("qa"))",
        ]
        let lines = body.components(separatedBy: "\n").filter { $0.trimmingCharacters(in: .whitespaces).hasPrefix("- ") }
        #expect(lines == expected, "\(body)")
        #expect(!body.contains("old-1"), "killed agents are left out")
        // An agent whose manager was killed moves to the top level rather than disappearing.
        try w.store.writer.write { db in try db.execute(sql: "UPDATE agent SET managerId = ? WHERE id = ?", arguments: [w.old.id, w.eng2.id]) }
        let moved = try w.render(.orgChart)
        #expect(moved.contains("\n- @eng-2 — "), "\(moved)")
    }

    @Test func rosterTable() throws {
        let w = try W()
        let body = try w.render(.roster)
        #expect(body.hasPrefix("# Roster\n\n\(Self.header)\n\n"))
        let rows = body.components(separatedBy: "\n").filter { $0.hasPrefix("|") }
        #expect(rows.first == "| Handle | Role | Team | Manager | State | Since |")
        #expect(rows.count == 2 + 5, "header, rule and every agent: \(rows)")
        let day = { (a: Agent) -> String in
            let f = DateFormatter(); f.locale = Locale(identifier: "en_US_POSIX"); f.timeZone = TimeZone(identifier: "UTC")
            f.dateFormat = "yyyy-MM-dd"; return f.string(from: a.createdAt)
        }
        let eng1 = try w.agent(w.eng1)
        #expect(rows.contains("| @eng-1 | \(w.title("engineer")) | payments | @mgr-1 | \(eng1.state.rawValue) | \(day(eng1)) |"), "\(rows)")
        let ceo = try w.agent(w.ceo)
        #expect(rows.contains("| @ceo | \(w.title("ceo")) | — | — | \(ceo.state.rawValue) | \(day(ceo)) |"), "\(rows)")
        let handles = rows.dropFirst(2).map { $0.split(separator: "|")[0].trimmingCharacters(in: .whitespaces) }
        #expect(handles == ["@ceo", "@eng-1", "@eng-2", "@mgr-1", "@old-1"], "sorted by handle")
        // Agent-written cell text cannot break the table.
        try w.store.writer.write { db in try db.execute(sql: "UPDATE agent SET team = 'a|b' WHERE id = ?", arguments: [w.eng2.id]) }
        #expect(try w.render(.roster).contains("| a\\|b |"))
    }

    // MARK: Decisions log

    @Test func decisionLogListsOnlyDecidedNonInfoTitles() throws {
        let w = try W()
        let approved = try w.ask(by: w.eng1, title: "Adopt the narwhal linter", summary: "SUMMARY-NARWHAL", status: .approved, decided: 120)
        let rejected = try w.ask(by: w.eng2, title: "Rewrite in Rust", status: .rejected, decidedBy: "@mgr-1", decided: 180)
        let rescinded = try w.ask(by: w.eng2, title: "Drop the cache", status: .rescinded, decidedBy: nil, decided: 200)
        _ = try w.ask(.info, by: w.eng1, title: "What is the heron budget", summary: "QUESTION-HERON", status: .answered, decided: 240)
        _ = try w.ask(by: w.eng1, title: "Pending pelican plan", status: .pendingOwner, decidedBy: nil, decided: 260)
        _ = try w.ask(by: w.eng1, title: "Expired egret plan", status: .expired, decidedBy: nil, decided: 270)
        try w.store.writer.write { db in
            try db.execute(sql: "UPDATE ask SET decidedBy = NULL, ownerDecidedAt = NULL, rescindedAt = ? WHERE id = ?",
                           arguments: [w.at(200), rescinded.id])
        }
        try w.store.recordMechanicalDecision(companyId: w.company.id, by: .agent(w.eng1.id), kind: .other, category: "tooling",
                                             title: "Use tabs\nnot spaces", summary: "MECH-SUMMARY", now: w.at(300))
        let body = try w.render(.decisionLog)
        #expect(body.hasPrefix("# Decisions log\n\n\(Self.header)\n\n"))
        let lines = body.components(separatedBy: "\n").filter { $0.hasPrefix("- ") }
        #expect(lines == [
            "- 2026-06-10 · recorded · @eng-1 — Use tabs not spaces",
            "- 2026-06-10 · \(rescinded.ref) Decision · rescinded by owner — Drop the cache",
            "- 2026-06-10 · \(rejected.ref) Decision · rejected by @mgr-1 — Rewrite in Rust",
            "- 2026-06-10 · \(approved.ref) Decision · approved by owner — Adopt the narwhal linter",
        ], "newest first: \(body)")
        for absent in ["heron", "QUESTION", "SUMMARY", "ANSWER-TEXT", "NOTE-TEXT", "pelican", "egret", "MECH-SUMMARY"] {
            #expect(!body.contains(absent), "\(absent)")
        }
        // Engine alerts never appear.
        try EngineAlerts.raise(store: w.store, text: "the osprey alert", now: w.at(400), reason: "doctor", companyId: w.company.id)
        try w.store.writer.write { db in
            try db.execute(sql: "UPDATE ask SET status = 'approved', decidedBy = 'owner', ownerDecidedAt = ? WHERE kind = 'engineAlert'",
                           arguments: [w.at(410)])
        }
        #expect(!(try w.render(.decisionLog)).contains("osprey"))
        // Agent text cannot form markup.
        _ = try w.ask(by: w.eng1, title: "Ship *it* [now](http://x) #1", status: .approved, decided: 500)
        #expect(try w.render(.decisionLog).contains("— Ship \\*it\\* \\[now\\](http://x) \\#1"))
    }

    @Test func decisionLogHidesReservedAndTermination() throws {
        let w = try W()
        let pricing = try w.ask(category: "pricing", by: w.mgr, title: "Raise the plover price", status: .approved, decided: 100)
        let staffing = try w.ask(category: "exec-staffing", by: w.ceo, title: "Hire a sandpiper CFO", status: .rejected, decided: 110)
        _ = try w.ask(category: "termination", by: w.mgr, title: "Part ways with the otter", status: .approved, decided: 120)
        let ordinary = try w.ask(by: w.eng1, title: "Adopt the gull formatter", status: .approved, decided: 130)
        let body = try w.render(.decisionLog)
        #expect(!body.contains("otter"), "termination asks never appear")
        let sections = KBMarkdown.sections(body, page: nil).filter { $0.heading != nil }
        #expect(sections.map(\.heading) == ["Decisions log", "Restricted decisions"])
        let open = try #require(sections.first), restricted = try #require(sections.last)
        #expect(open.text.contains("\(ordinary.ref) Decision · approved by owner — Adopt the gull formatter"))
        #expect(!open.text.contains("plover")); #expect(!open.text.contains("sandpiper"))
        #expect(restricted.marker == ["@executive"])
        #expect(restricted.text.contains("\(pricing.ref) Decision · approved by owner — Raise the plover price"))
        #expect(restricted.text.contains("\(staffing.ref) Decision · rejected by owner — Hire a sandpiper CFO"))

        // Through the handbook: engineers don't see the restricted section, executives and the owner do.
        try w.store.refreshAutoPages(companyId: w.company.id, now: w.at(200))
        let eng = try #require(try w.store.kbRead(companyId: w.company.id, reader: .agent(w.eng1.id), path: "Decisions log"))
        #expect(eng.text.contains("gull")); #expect(!eng.text.contains("plover")); #expect(!eng.text.contains("sandpiper"))
        #expect(eng.hiddenSections == 1)
        let ceo = try #require(try w.store.kbRead(companyId: w.company.id, reader: .agent(w.ceo.id), path: "Decisions log"))
        #expect(ceo.text.contains("plover")); #expect(!ceo.text.contains("otter"))
        let owner = try #require(try w.store.kbRead(companyId: w.company.id, reader: .owner, path: "Decisions log"))
        #expect(owner.text.contains("sandpiper")); #expect(!owner.text.contains("otter"))
        // Search agrees.
        let hits = try MemoryIndex(store: w.store).search(companyId: w.company.id, scope: .agent(w.eng1.id), query: "plover",
                                                          sources: [.kb], now: w.at(300))
        #expect(hits.isEmpty)
    }

